export function getTtsVoiceForLanguage(langCodeOrName) {
  if (!langCodeOrName) return 'pt-BR-FranciscaNeural';
  const found = ALL_LANGUAGES.find(
    (l) =>
      l.code.toLowerCase() === langCodeOrName.toLowerCase() ||
      l.name.toLowerCase() === langCodeOrName.toLowerCase()
  );
  if (found) return found.ttsVoice;
  return 'pt-BR-FranciscaNeural';
}
